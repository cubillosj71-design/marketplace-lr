-- Name: v_reserva_reporte; Type: VIEW; Schema: public; Owner: -
--

CREATE VIEW public.v_reserva_reporte AS
 SELECT r.id,
    r.publicacion_id,
    p.titulo,
    COALESCE(c.nombre, 'Sin ciudad'::character varying) AS ciudad,
    COALESCE(t.nombre, 'Sin tipo'::character varying) AS tipo,
    r.huesped_id,
    u.nombre_completo AS huesped,
    r.creada,
    r.fecha_llegada,
    r.fecha_salida,
    co.noches,
    r.estado,
    r.total,
    co.tarifa_servicio,
    (COALESCE(ca.valor_devolucion, (0)::numeric))::numeric(12,2) AS valor_devolucion,
    (
        CASE
            WHEN ((r.estado)::text = ANY ((ARRAY['CONFIRMADA'::character varying, 'COMPLETADA'::character varying, 'EN_REVISION'::character varying])::text[])) THEN r.total
            WHEN ((r.estado)::text = 'CANCELADA'::text) THEN (r.total - COALESCE(ca.valor_devolucion, (0)::numeric))
            ELSE (0)::numeric
        END)::numeric(12,2) AS monto_bruto,
    (
        CASE
            WHEN ((r.estado)::text = ANY ((ARRAY['CONFIRMADA'::character varying, 'COMPLETADA'::character varying, 'EN_REVISION'::character varying])::text[])) THEN co.tarifa_servicio
            WHEN ((r.estado)::text = 'CANCELADA'::text) THEN round((co.tarifa_servicio * ((1)::numeric - (COALESCE(ca.valor_devolucion, (0)::numeric) / NULLIF(r.total, (0)::numeric)))), 2)
            ELSE (0)::numeric
        END)::numeric(12,2) AS ingreso_plataforma
   FROM ((((((public.reserva r
     JOIN public.cotizacion co ON ((co.id = r.cotizacion_id)))
     JOIN public.publicacion p ON ((p.id = r.publicacion_id)))
     LEFT JOIN public.ciudad c ON ((c.id = p.ciudad_id)))
     LEFT JOIN public.tipo_alojamiento t ON ((t.id = p.tipo_alojamiento_id)))
     JOIN public.usuario u ON ((u.id = r.huesped_id)))
     LEFT JOIN public.cancelacion ca ON ((ca.reserva_id = r.id)));


